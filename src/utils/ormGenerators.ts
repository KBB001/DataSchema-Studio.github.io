import { Column, Relationship, Schema, SqlDialect, Table } from '../types';

/**
 * Normalizes identifier to safe camelCase or PascalCase for ORMs
 */
export function toCamelCase(str: string): string {
  const clean = str.replace(/[^a-zA-Z0-9_\u0400-\u04FF]/g, '_');
  return clean
    .replace(/^_+|_+$/g, '')
    .split('_')
    .map((word, index) => {
      if (!word) return '';
      if (index === 0) {
        return word.charAt(0).toLowerCase() + word.slice(1);
      }
      return word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join('');
}

export function toPascalCase(str: string): string {
  const camel = toCamelCase(str);
  if (!camel) return 'Model';
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

/**
 * 1. PRISMA SCHEMA GENERATOR
 * Generates production-ready schema.prisma with models, relations, @map and attributes
 */
export function generatePrismaSchema(
  schema: Schema,
  options: {
    dialect?: SqlDialect;
    preserveSnakeCase?: boolean;
    includeComments?: boolean;
  } = {}
): string {
  const { dialect = schema.dialect || 'PostgreSQL', preserveSnakeCase = false, includeComments = true } = options;

  let provider = 'postgresql';
  if (dialect === 'MySQL') provider = 'mysql';
  else if (dialect === 'SQLite') provider = 'sqlite';
  else if (dialect === 'MSSQL') provider = 'sqlserver';

  let output = `// Prisma Schema generated by SQL & Schema Studio v2.0
// Docs: https://pris.ly/d/prisma-schema

generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "${provider}"
  url      = env("DATABASE_URL")
}
\n`;

  for (const table of schema.tables) {
    const modelName = preserveSnakeCase ? table.name.replace(/\s+/g, '_') : toPascalCase(table.name);
    const tableMapped = modelName !== table.name ? `\n  @@map("${table.name}")` : '';

    if (includeComments && table.comment) {
      output += `/// ${table.comment}\n`;
    }
    output += `model ${modelName} {\n`;

    // Columns
    for (const col of table.columns) {
      const fieldName = preserveSnakeCase ? col.name.replace(/\s+/g, '_') : toCamelCase(col.name);
      const isPk = col.isPk;
      const isUnique = col.isUnique && !isPk;
      const isNullable = col.isNullable && !isPk;

      let prismaType = 'String';
      let defaultAttr = '';

      switch (col.type) {
        case 'INT':
          prismaType = 'Int';
          break;
        case 'BIGINT':
          prismaType = 'BigInt';
          break;
        case 'SERIAL':
          prismaType = 'Int';
          if (isPk) defaultAttr = ' @default(autoincrement())';
          break;
        case 'BIGSERIAL':
          prismaType = 'BigInt';
          if (isPk) defaultAttr = ' @default(autoincrement())';
          break;
        case 'VARCHAR':
        case 'TEXT':
          prismaType = 'String';
          break;
        case 'UUID':
          prismaType = 'String';
          if (isPk) defaultAttr = ' @default(uuid())';
          break;
        case 'BOOLEAN':
          prismaType = 'Boolean';
          if (col.defaultValue !== undefined && col.defaultValue !== '') {
            const boolVal = col.defaultValue.toLowerCase() === 'true' || col.defaultValue === '1';
            defaultAttr = ` @default(${boolVal})`;
          }
          break;
        case 'DECIMAL':
          prismaType = 'Decimal';
          break;
        case 'FLOAT':
          prismaType = 'Float';
          break;
        case 'DATE':
        case 'TIMESTAMP':
        case 'TIMESTAMPTZ':
          prismaType = 'DateTime';
          if (col.defaultValue && /now\(\)|current_timestamp/i.test(col.defaultValue)) {
            defaultAttr = ' @default(now())';
          }
          break;
        case 'JSONB':
          prismaType = 'Json';
          break;
        case 'ENUM':
          prismaType = 'String';
          break;
        default:
          prismaType = 'String';
      }

      if (col.defaultValue && !defaultAttr) {
        if (col.defaultValue.toLowerCase() === 'now()' || col.defaultValue.toLowerCase() === 'current_timestamp') {
          defaultAttr = ' @default(now())';
        } else if (/^\d+$/.test(col.defaultValue)) {
          defaultAttr = ` @default(${col.defaultValue})`;
        } else if (/^true|false$/i.test(col.defaultValue)) {
          defaultAttr = ` @default(${col.defaultValue.toLowerCase()})`;
        } else if (col.defaultValue.startsWith("'") && col.defaultValue.endsWith("'")) {
          defaultAttr = ` @default(${JSON.stringify(col.defaultValue.slice(1, -1))})`;
        }
      }

      const idAttr = isPk ? ' @id' : '';
      const uniqueAttr = isUnique ? ' @unique' : '';
      const mapAttr = fieldName !== col.name ? ` @map("${col.name}")` : '';
      const typeStr = `${prismaType}${isNullable ? '?' : ''}`;

      if (includeComments && col.comment) {
        output += `  /// ${col.comment}\n`;
      }
      output += `  ${fieldName.padEnd(20)} ${typeStr}${idAttr}${defaultAttr}${uniqueAttr}${mapAttr}\n`;
    }

    // Outgoing Relations (where this table holds the foreign key)
    const outgoingRels = schema.relationships.filter((r) => r.sourceTableId === table.id);
    for (const rel of outgoingRels) {
      const targetTable = schema.tables.find((t) => t.id === rel.targetTableId);
      const sourceCol = table.columns.find((c) => c.id === rel.sourceColumnId);
      const targetCol = targetTable?.columns.find((c) => c.id === rel.targetColumnId);

      if (targetTable && sourceCol && targetCol) {
        const targetModelName = preserveSnakeCase ? targetTable.name.replace(/\s+/g, '_') : toPascalCase(targetTable.name);
        const relFieldName = preserveSnakeCase
          ? `${targetTable.name.toLowerCase()}_rel`
          : toCamelCase(`${targetTable.name}`);
        const fkFieldName = preserveSnakeCase ? sourceCol.name.replace(/\s+/g, '_') : toCamelCase(sourceCol.name);
        const targetPkFieldName = preserveSnakeCase ? targetCol.name.replace(/\s+/g, '_') : toCamelCase(targetCol.name);
        const cascadeOpt = rel.onDelete ? `onDelete: ${rel.onDelete === 'SET NULL' ? 'SetNull' : rel.onDelete === 'NO ACTION' ? 'NoAction' : rel.onDelete === 'RESTRICT' ? 'Restrict' : 'Cascade'}` : '';

        const relOpts = [`fields: [${fkFieldName}]`, `references: [${targetPkFieldName}]`];
        if (cascadeOpt) relOpts.push(cascadeOpt);

        output += `  ${relFieldName.padEnd(20)} ${targetModelName}${sourceCol.isNullable ? '?' : ''} @relation(${relOpts.join(', ')})\n`;
      }
    }

    // Incoming Relations (where other tables reference this table)
    const incomingRels = schema.relationships.filter((r) => r.targetTableId === table.id);
    for (const rel of incomingRels) {
      const sourceTable = schema.tables.find((t) => t.id === rel.sourceTableId);
      if (sourceTable) {
        const sourceModelName = preserveSnakeCase ? sourceTable.name.replace(/\s+/g, '_') : toPascalCase(sourceTable.name);
        const relListField = preserveSnakeCase
          ? `${sourceTable.name.toLowerCase()}_list`
          : toCamelCase(`${sourceTable.name}List`);
        const isOneToOne = rel.type === '1:1';
        output += `  ${relListField.padEnd(20)} ${sourceModelName}${isOneToOne ? '?' : '[]'}\n`;
      }
    }

    if (tableMapped) {
      output += tableMapped;
    }

    output += `}\n\n`;
  }

  return output.trim();
}

/**
 * 2. DRIZZLE ORM GENERATOR
 * Generates modern schema.ts with pgTable/mysqlTable/sqliteTable and relations()
 */
export function generateDrizzleSchema(
  schema: Schema,
  options: {
    dialect?: SqlDialect;
  } = {}
): string {
  const { dialect = schema.dialect || 'PostgreSQL' } = options;

  let pkgName = 'drizzle-orm/pg-core';
  let tableFn = 'pgTable';

  if (dialect === 'MySQL') {
    pkgName = 'drizzle-orm/mysql-core';
    tableFn = 'mysqlTable';
  } else if (dialect === 'SQLite') {
    pkgName = 'drizzle-orm/sqlite-core';
    tableFn = 'sqliteTable';
  }

  let code = `// Drizzle ORM Schema generated by SQL & Schema Studio v2.0
// Docs: https://orm.drizzle.team/docs/overview

`;

  if (dialect === 'MySQL') {
    code += `import { ${tableFn}, int, varchar, text, decimal, double, boolean, date, datetime, json } from '${pkgName}';\n`;
  } else if (dialect === 'SQLite') {
    code += `import { ${tableFn}, integer, text, real, blob } from '${pkgName}';\n`;
  } else {
    code += `import { ${tableFn}, serial, bigserial, integer, bigint, varchar, text, boolean, decimal, doublePrecision, timestamp, date, jsonb, uuid } from '${pkgName}';\n`;
  }
  code += `import { relations } from 'drizzle-orm';\n\n`;

  // Tables
  for (const table of schema.tables) {
    const varName = toCamelCase(table.name);
    code += `export const ${varName} = ${tableFn}('${table.name}', {\n`;

    for (const col of table.columns) {
      const colVar = toCamelCase(col.name);
      const isPk = col.isPk;
      let colDef = '';

      if (dialect === 'MySQL') {
        switch (col.type) {
          case 'INT':
          case 'SERIAL':
            colDef = `int('${col.name}')`;
            if (col.type === 'SERIAL') colDef += '.autoincrement()';
            break;
          case 'BIGINT':
          case 'BIGSERIAL':
            colDef = `int('${col.name}')`;
            if (col.type === 'BIGSERIAL') colDef += '.autoincrement()';
            break;
          case 'VARCHAR':
            colDef = `varchar('${col.name}', { length: ${col.lengthOrPrecision || 255} })`;
            break;
          case 'TEXT':
            colDef = `text('${col.name}')`;
            break;
          case 'UUID':
            colDef = `varchar('${col.name}', { length: 36 })`;
            break;
          case 'BOOLEAN':
            colDef = `boolean('${col.name}')`;
            break;
          case 'DECIMAL':
            colDef = `decimal('${col.name}', { precision: 12, scale: 2 })`;
            break;
          case 'FLOAT':
            colDef = `double('${col.name}')`;
            break;
          case 'DATE':
            colDef = `date('${col.name}')`;
            break;
          case 'TIMESTAMP':
          case 'TIMESTAMPTZ':
            colDef = `datetime('${col.name}')`;
            break;
          case 'JSONB':
            colDef = `json('${col.name}')`;
            break;
          default:
            colDef = `varchar('${col.name}', { length: 255 })`;
        }
      } else if (dialect === 'SQLite') {
        switch (col.type) {
          case 'INT':
          case 'BIGINT':
          case 'SERIAL':
          case 'BIGSERIAL':
            colDef = `integer('${col.name}')`;
            break;
          case 'BOOLEAN':
            colDef = `integer('${col.name}', { mode: 'boolean' })`;
            break;
          case 'FLOAT':
          case 'DECIMAL':
            colDef = `real('${col.name}')`;
            break;
          case 'DATE':
          case 'TIMESTAMP':
          case 'TIMESTAMPTZ':
            colDef = `text('${col.name}')`;
            break;
          default:
            colDef = `text('${col.name}')`;
        }
      } else {
        // PostgreSQL
        switch (col.type) {
          case 'SERIAL':
            colDef = `serial('${col.name}')`;
            break;
          case 'BIGSERIAL':
            colDef = `bigserial('${col.name}', { mode: 'bigint' })`;
            break;
          case 'INT':
            colDef = `integer('${col.name}')`;
            break;
          case 'BIGINT':
            colDef = `bigint('${col.name}', { mode: 'bigint' })`;
            break;
          case 'VARCHAR':
            colDef = `varchar('${col.name}', { length: ${col.lengthOrPrecision || 255} })`;
            break;
          case 'TEXT':
            colDef = `text('${col.name}')`;
            break;
          case 'UUID':
            colDef = `uuid('${col.name}')`;
            if (isPk) colDef += '.defaultRandom()';
            break;
          case 'BOOLEAN':
            colDef = `boolean('${col.name}')`;
            break;
          case 'DECIMAL':
            colDef = `decimal('${col.name}', { precision: 12, scale: 2 })`;
            break;
          case 'FLOAT':
            colDef = `doublePrecision('${col.name}')`;
            break;
          case 'DATE':
            colDef = `date('${col.name}')`;
            break;
          case 'TIMESTAMP':
          case 'TIMESTAMPTZ':
            colDef = `timestamp('${col.name}', { withTimezone: ${col.type === 'TIMESTAMPTZ'} })`;
            if (col.defaultValue && /now\(\)|current_timestamp/i.test(col.defaultValue)) {
              colDef += '.defaultNow()';
            }
            break;
          case 'JSONB':
            colDef = `jsonb('${col.name}')`;
            break;
          default:
            colDef = `varchar('${col.name}', { length: 255 })`;
        }
      }

      if (isPk) {
        colDef += '.primaryKey()';
      }
      if (!col.isNullable && !isPk) {
        colDef += '.notNull()';
      }
      if (col.isUnique && !isPk) {
        colDef += '.unique()';
      }

      code += `  ${colVar}: ${colDef},\n`;
    }

    code += `});\n\n`;
  }

  // Relations
  for (const table of schema.tables) {
    const varName = toCamelCase(table.name);
    const outgoingRels = schema.relationships.filter((r) => r.sourceTableId === table.id);
    const incomingRels = schema.relationships.filter((r) => r.targetTableId === table.id);

    if (outgoingRels.length === 0 && incomingRels.length === 0) continue;

    code += `export const ${varName}Relations = relations(${varName}, ({ one, many }) => ({\n`;

    // One-to relations (outgoing FK)
    for (const rel of outgoingRels) {
      const targetTable = schema.tables.find((t) => t.id === rel.targetTableId);
      const sourceCol = table.columns.find((c) => c.id === rel.sourceColumnId);
      const targetCol = targetTable?.columns.find((c) => c.id === rel.targetColumnId);
      if (targetTable && sourceCol && targetCol) {
        const targetVar = toCamelCase(targetTable.name);
        const relName = toCamelCase(targetTable.name);
        code += `  ${relName}: one(${targetVar}, {\n`;
        code += `    fields: [${varName}.${toCamelCase(sourceCol.name)}],\n`;
        code += `    references: [${targetVar}.${toCamelCase(targetCol.name)}],\n`;
        code += `  }),\n`;
      }
    }

    // Many relations (incoming FK)
    for (const rel of incomingRels) {
      const sourceTable = schema.tables.find((t) => t.id === rel.sourceTableId);
      if (sourceTable) {
        const sourceVar = toCamelCase(sourceTable.name);
        const relName = toCamelCase(`${sourceTable.name}List`);
        code += `  ${relName}: many(${sourceVar}),\n`;
      }
    }

    code += `}));\n\n`;
  }

  return code.trim();
}

/**
 * 3. TYPEORM ENTITY GENERATOR
 * Generates TypeScript Entity classes with decorator metadata
 */
export function generateTypeOrmSchema(schema: Schema): string {
  let code = `// TypeORM Entity classes generated by SQL & Schema Studio v2.0
// Docs: https://typeorm.io/entities

import { Entity, PrimaryGeneratedColumn, PrimaryColumn, Column, CreateDateColumn, UpdateDateColumn, ManyToOne, OneToMany, JoinColumn } from 'typeorm';

`;

  for (const table of schema.tables) {
    const className = toPascalCase(table.name);

    if (table.comment) {
      code += `/** ${table.comment} */\n`;
    }
    code += `@Entity('${table.name}')\nexport class ${className} {\n`;

    for (const col of table.columns) {
      const propName = toCamelCase(col.name);
      const isPk = col.isPk;

      let tsType = 'string';
      if (col.type === 'INT' || col.type === 'BIGINT' || col.type === 'SERIAL' || col.type === 'BIGSERIAL' || col.type === 'FLOAT') {
        tsType = 'number';
      } else if (col.type === 'BOOLEAN') {
        tsType = 'boolean';
      } else if (col.type === 'DATE' || col.type === 'TIMESTAMP' || col.type === 'TIMESTAMPTZ') {
        tsType = 'Date';
      } else if (col.type === 'JSONB') {
        tsType = 'Record<string, any>';
      }

      if (isPk) {
        if (col.type === 'SERIAL' || col.type === 'BIGSERIAL') {
          code += `  @PrimaryGeneratedColumn()\n`;
        } else if (col.type === 'UUID') {
          code += `  @PrimaryGeneratedColumn('uuid')\n`;
        } else {
          code += `  @PrimaryColumn({ name: '${col.name}' })\n`;
        }
      } else {
        const colOpts: string[] = [`name: '${col.name}'`];
        if (col.isNullable) colOpts.push('nullable: true');
        if (col.isUnique) colOpts.push('unique: true');
        if (col.comment) colOpts.push(`comment: ${JSON.stringify(col.comment)}`);

        code += `  @Column({ ${colOpts.join(', ')} })\n`;
      }

      code += `  ${propName}${col.isNullable && !isPk ? '?' : ''}: ${tsType};\n\n`;
    }

    // Relations
    const outgoingRels = schema.relationships.filter((r) => r.sourceTableId === table.id);
    for (const rel of outgoingRels) {
      const targetTable = schema.tables.find((t) => t.id === rel.targetTableId);
      const sourceCol = table.columns.find((c) => c.id === rel.sourceColumnId);
      if (targetTable && sourceCol) {
        const targetClass = toPascalCase(targetTable.name);
        const relProp = toCamelCase(targetTable.name);
        code += `  @ManyToOne(() => ${targetClass}, { onDelete: '${rel.onDelete || 'CASCADE'}' })\n`;
        code += `  @JoinColumn({ name: '${sourceCol.name}' })\n`;
        code += `  ${relProp}?: ${targetClass};\n\n`;
      }
    }

    code += `}\n\n`;
  }

  return code.trim();
}

/**
 * 4. DATA DICTIONARY GENERATOR
 * Generates structured Markdown documentation with table metrics and column specifications
 */
export function generateDataDictionaryMarkdown(schema: Schema): string {
  const totalTables = schema.tables.length;
  const totalCols = schema.tables.reduce((acc, t) => acc + t.columns.length, 0);
  const totalRels = schema.relationships.length;

  let md = `# Словарь данных (Data Dictionary)\n\n`;
  md += `> Документация архитектуры базы данных создана: ${new Date().toLocaleDateString('ru-RU')} в **SQL & Schema Studio v2.0**.\n\n`;
  md += `### Сводка схемы\n`;
  md += `- **Целевая СУБД:** \`${schema.dialect || 'PostgreSQL'}\`\n`;
  md += `- **Количество таблиц:** **${totalTables}**\n`;
  md += `- **Всего колонок:** **${totalCols}**\n`;
  md += `- **Связей (Foreign Keys):** **${totalRels}**\n\n`;

  md += `## Список таблиц\n\n`;
  md += `| # | Таблица | Описание / Назначение | Колонок | Связей |\n`;
  md += `| :---: | :--- | :--- | :---: | :---: |\n`;

  schema.tables.forEach((t, i) => {
    const relsCount = schema.relationships.filter(
      (r) => r.sourceTableId === t.id || r.targetTableId === t.id
    ).length;
    md += `| ${i + 1} | [**\`${t.name}\`**](#таблица-${t.name.toLowerCase().replace(/[^a-zA-Z0-9\u0400-\u04FF]/g, '-')}) | ${t.comment || '*Не указано*'} | ${t.columns.length} | ${relsCount} |\n`;
  });

  md += `\n---\n\n## Детальная спецификация таблиц\n\n`;

  for (const table of schema.tables) {
    const tableIdAnchor = table.name.toLowerCase().replace(/[^a-zA-Z0-9\u0400-\u04FF]/g, '-');
    md += `### Таблица: \`${table.name}\`\n\n`;
    if (table.comment) {
      md += `**Назначение:** ${table.comment}\n\n`;
    }

    md += `| Колонка | Тип данных | Обязательность | Ключи | По умолчанию | Описание |\n`;
    md += `| :--- | :--- | :---: | :---: | :--- | :--- |\n`;

    for (const col of table.columns) {
      const typeStr = col.lengthOrPrecision ? `${col.type}(${col.lengthOrPrecision})` : col.type;
      const nullableStr = col.isNullable ? 'NULL' : '**NOT NULL**';

      const keyBadges: string[] = [];
      if (col.isPk) keyBadges.push('🔑 **PK**');
      if (col.isFk) keyBadges.push('🔗 **FK**');
      if (col.isUnique && !col.isPk) keyBadges.push('⚡ Unique');
      const keysStr = keyBadges.length > 0 ? keyBadges.join(', ') : '-';

      const defVal = col.defaultValue ? `\`${col.defaultValue}\`` : '-';
      const commentStr = col.comment || '-';

      md += `| \`${col.name}\` | \`${typeStr}\` | ${nullableStr} | ${keysStr} | ${defVal} | ${commentStr} |\n`;
    }

    // Foreign keys from this table
    const outgoing = schema.relationships.filter((r) => r.sourceTableId === table.id);
    if (outgoing.length > 0) {
      md += `\n**Внешние ключи (Foreign Keys):**\n`;
      for (const rel of outgoing) {
        const targetTable = schema.tables.find((t) => t.id === rel.targetTableId);
        const sourceCol = table.columns.find((c) => c.id === rel.sourceColumnId);
        const targetCol = targetTable?.columns.find((c) => c.id === rel.targetColumnId);
        if (targetTable && sourceCol && targetCol) {
          md += `- Поле \`${sourceCol.name}\` ➔ \`${targetTable.name}.${targetCol.name}\` (ON DELETE ${rel.onDelete || 'CASCADE'}, ON UPDATE ${rel.onUpdate || 'CASCADE'})\n`;
        }
      }
    }

    md += `\n`;
  }

  return md;
}

/**
 * 5. SCHEMA DIFF & MIGRATION SCRIPT GENERATOR
 * Calculates differences between two schemas and creates migration statements
 */
export interface SchemaDiffResult {
  addedTables: Table[];
  removedTables: Table[];
  modifiedTables: {
    table: Table;
    addedColumns: Column[];
    removedColumns: Column[];
    modifiedColumns: { oldCol: Column; newCol: Column }[];
  }[];
  addedRelationships: Relationship[];
  removedRelationships: Relationship[];
  migrationSql: string;
  hasChanges: boolean;
}

export function calculateSchemaDiff(
  oldSchema: Schema,
  newSchema: Schema,
  dialect: SqlDialect = newSchema.dialect || 'PostgreSQL'
): SchemaDiffResult {
  const oldTablesMap = new Map<string, Table>();
  oldSchema.tables.forEach((t) => oldTablesMap.set(t.name.toLowerCase(), t));

  const newTablesMap = new Map<string, Table>();
  newSchema.tables.forEach((t) => newTablesMap.set(t.name.toLowerCase(), t));

  const addedTables: Table[] = [];
  const removedTables: Table[] = [];
  const modifiedTables: SchemaDiffResult['modifiedTables'] = [];

  // Check new tables against old
  for (const [name, newT] of newTablesMap.entries()) {
    const oldT = oldTablesMap.get(name);
    if (!oldT) {
      addedTables.push(newT);
    } else {
      // Check column changes
      const oldColsMap = new Map<string, Column>();
      oldT.columns.forEach((c) => oldColsMap.set(c.name.toLowerCase(), c));

      const newColsMap = new Map<string, Column>();
      newT.columns.forEach((c) => newColsMap.set(c.name.toLowerCase(), c));

      const addedCols: Column[] = [];
      const removedCols: Column[] = [];
      const modifiedCols: { oldCol: Column; newCol: Column }[] = [];

      for (const [colName, nCol] of newColsMap.entries()) {
        const oCol = oldColsMap.get(colName);
        if (!oCol) {
          addedCols.push(nCol);
        } else {
          // Check for type, nullable, or default value modifications
          if (
            oCol.type !== nCol.type ||
            oCol.lengthOrPrecision !== nCol.lengthOrPrecision ||
            oCol.isNullable !== nCol.isNullable ||
            oCol.defaultValue !== nCol.defaultValue
          ) {
            modifiedCols.push({ oldCol: oCol, newCol: nCol });
          }
        }
      }

      for (const [colName, oCol] of oldColsMap.entries()) {
        if (!newColsMap.has(colName)) {
          removedCols.push(oCol);
        }
      }

      if (addedCols.length > 0 || removedCols.length > 0 || modifiedCols.length > 0) {
        modifiedTables.push({
          table: newT,
          addedColumns: addedCols,
          removedColumns: removedCols,
          modifiedColumns: modifiedCols,
        });
      }
    }
  }

  // Check removed tables
  for (const [name, oldT] of oldTablesMap.entries()) {
    if (!newTablesMap.has(name)) {
      removedTables.push(oldT);
    }
  }

  // Compare relationships
  const addedRelationships: Relationship[] = [];
  const removedRelationships: Relationship[] = [];

  const relKey = (r: Relationship, s: Schema) => {
    const srcT = s.tables.find((t) => t.id === r.sourceTableId)?.name.toLowerCase();
    const tgtT = s.tables.find((t) => t.id === r.targetTableId)?.name.toLowerCase();
    return `${srcT}_to_${tgtT}_${r.sourceColumnId}_${r.targetColumnId}`;
  };

  const oldRelKeys = new Set(oldSchema.relationships.map((r) => relKey(r, oldSchema)));
  const newRelKeys = new Set(newSchema.relationships.map((r) => relKey(r, newSchema)));

  for (const nRel of newSchema.relationships) {
    if (!oldRelKeys.has(relKey(nRel, newSchema))) {
      addedRelationships.push(nRel);
    }
  }
  for (const oRel of oldSchema.relationships) {
    if (!newRelKeys.has(relKey(oRel, oldSchema))) {
      removedRelationships.push(oRel);
    }
  }

  const hasChanges =
    addedTables.length > 0 ||
    removedTables.length > 0 ||
    modifiedTables.length > 0 ||
    addedRelationships.length > 0 ||
    removedRelationships.length > 0;

  // Build migration SQL script
  let migrationSql = `-- ========================================================\n`;
  migrationSql += `-- МИГРАЦИЯ СХЕМЫ (DIALECT: ${dialect})\n`;
  migrationSql += `-- Создано: ${new Date().toLocaleString('ru-RU')}\n`;
  migrationSql += `-- ========================================================\n\n`;

  if (!hasChanges) {
    migrationSql += `-- Схемы идентичны. Изменений структуры не обнаружено.\n`;
  } else {
    // 1. ADD NEW TABLES
    if (addedTables.length > 0) {
      migrationSql += `-- 1. СОЗДАНИЕ НОВЫХ ТАБЛИЦ\n`;
      for (const t of addedTables) {
        migrationSql += `CREATE TABLE ${t.name} (\n`;
        const colDefs = t.columns.map((c) => {
          let line = `    ${c.name} ${c.lengthOrPrecision ? `${c.type}(${c.lengthOrPrecision})` : c.type}`;
          if (c.isPk) line += ' PRIMARY KEY';
          if (!c.isNullable && !c.isPk) line += ' NOT NULL';
          if (c.defaultValue) line += ` DEFAULT ${c.defaultValue}`;
          return line;
        });
        migrationSql += colDefs.join(',\n') + '\n);\n\n';
      }
    }

    // 2. ALTER EXISTING TABLES
    if (modifiedTables.length > 0) {
      migrationSql += `-- 2. МОДИФИКАЦИЯ СУЩЕСТВУЮЩИХ ТАБЛИЦ\n`;
      for (const mod of modifiedTables) {
        // Added columns
        for (const col of mod.addedColumns) {
          const typeStr = col.lengthOrPrecision ? `${col.type}(${col.lengthOrPrecision})` : col.type;
          const notNull = !col.isNullable ? ' NOT NULL' : '';
          const defVal = col.defaultValue ? ` DEFAULT ${col.defaultValue}` : '';
          migrationSql += `ALTER TABLE ${mod.table.name} ADD COLUMN ${col.name} ${typeStr}${defVal}${notNull};\n`;
        }

        // Modified columns
        for (const m of mod.modifiedColumns) {
          const typeStr = m.newCol.lengthOrPrecision ? `${m.newCol.type}(${m.newCol.lengthOrPrecision})` : m.newCol.type;
          if (dialect === 'PostgreSQL') {
            migrationSql += `ALTER TABLE ${mod.table.name} ALTER COLUMN ${m.newCol.name} TYPE ${typeStr};\n`;
            if (m.oldCol.isNullable !== m.newCol.isNullable) {
              migrationSql += `ALTER TABLE ${mod.table.name} ALTER COLUMN ${m.newCol.name} ${m.newCol.isNullable ? 'DROP NOT NULL' : 'SET NOT NULL'};\n`;
            }
          } else if (dialect === 'MySQL') {
            migrationSql += `ALTER TABLE ${mod.table.name} MODIFY COLUMN ${m.newCol.name} ${typeStr}${!m.newCol.isNullable ? ' NOT NULL' : ''};\n`;
          } else {
            migrationSql += `ALTER TABLE ${mod.table.name} ALTER COLUMN ${m.newCol.name} ${typeStr};\n`;
          }
        }

        // Dropped columns (commented for safety)
        for (const col of mod.removedColumns) {
          migrationSql += `-- ОСТОРОЖНО: Удаление данных!\n-- ALTER TABLE ${mod.table.name} DROP COLUMN ${col.name};\n`;
        }

        migrationSql += '\n';
      }
    }

    // 3. ADD NEW FOREIGN KEYS
    if (addedRelationships.length > 0) {
      migrationSql += `-- 3. ДОБАВЛЕНИЕ ВНЕШНИХ КЛЮЧЕЙ\n`;
      for (const rel of addedRelationships) {
        const srcTable = newSchema.tables.find((t) => t.id === rel.sourceTableId);
        const tgtTable = newSchema.tables.find((t) => t.id === rel.targetTableId);
        const srcCol = srcTable?.columns.find((c) => c.id === rel.sourceColumnId);
        const tgtCol = tgtTable?.columns.find((c) => c.id === rel.targetColumnId);

        if (srcTable && tgtTable && srcCol && tgtCol) {
          const fkName = rel.name || `fk_${srcTable.name}_${srcCol.name}`;
          migrationSql += `ALTER TABLE ${srcTable.name} ADD CONSTRAINT ${fkName} FOREIGN KEY (${srcCol.name}) REFERENCES ${tgtTable.name}(${tgtCol.name}) ON DELETE ${rel.onDelete || 'CASCADE'};\n`;
        }
      }
      migrationSql += '\n';
    }

    // 4. DROPPED TABLES (commented for safety)
    if (removedTables.length > 0) {
      migrationSql += `-- 4. УДАЛЕННЫЕ ТАБЛИЦЫ (закомментировано для защиты от случайной потери данных)\n`;
      for (const t of removedTables) {
        migrationSql += `-- DROP TABLE IF EXISTS ${t.name} CASCADE;\n`;
      }
    }
  }

  return {
    addedTables,
    removedTables,
    modifiedTables,
    addedRelationships,
    removedRelationships,
    migrationSql,
    hasChanges,
  };
}
